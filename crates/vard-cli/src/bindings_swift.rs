//! `vard bindings --swift`: the iOS counterpart of the Kotlin base class.
//!
//! One self-contained file: `Codable` structs and `String`-backed enums for the data, a
//! protocol with one method per `extern fn` (a wrong type is a Swift compile error), a
//! `call(name, json)` dispatcher matching the C ABI host callback (`vard_set_host`), callback
//! wrappers that answer through `vard_callback`, and `emit…` helpers for `extern event`s.
//! Support types live in a per-module namespace (`<Class>Vard`) so several generated
//! modules can share one target.

use crate::bindings::Opts;
use std::collections::BTreeSet;
use vard_lang::ast::{Program, TypeRef};
use vard_lang::Compilation;

const KEYWORDS: &[&str] = &[
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init", "inout", "internal", "let", "open", "operator", "private", "protocol",
    "public", "rethrows", "static", "struct", "subscript", "typealias", "var", "break", "case", "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard",
    "if", "in", "repeat", "return", "switch", "where", "while", "as", "catch", "false", "is", "nil", "self", "Self", "super", "throw", "throws", "true", "try", "Type",
];

fn ident(s: &str) -> String {
    if KEYWORDS.contains(&s) {
        format!("`{}`", s)
    } else {
        s.to_string()
    }
}

/// Vard type names that would shadow Swift standard types get a `V` prefix (JSON is unaffected).
fn sw_name(n: &str) -> String {
    const CLASH: &[&str] = &["String", "Int", "Double", "Float", "Bool", "Array", "Dictionary", "Optional", "Result", "Error", "Data", "Date", "URL", "Set", "Character", "Any", "Void", "Never"];
    if CLASH.contains(&n) {
        format!("V{}", n)
    } else {
        n.to_string()
    }
}

fn sw_type(t: &TypeRef, ns: &str) -> String {
    match t {
        TypeRef::Named(n, _) => match n.as_str() {
            "Int" => "Int".into(),
            "Float" => "Double".into(),
            "String" | "Color" => "String".into(),
            "Bool" => "Bool".into(),
            other => sw_name(other),
        },
        TypeRef::List(x) => format!("[{}]", sw_type(x, ns)),
        TypeRef::Map(x) => format!("[String: {}]", sw_type(x, ns)),
        TypeRef::Opt(x) => format!("{}?", sw_type(x, ns)),
        TypeRef::Fn(ps, _) => match ps.len() {
            0 => format!("{}.Signal", ns),
            1 => format!("{}.Result<{}>", ns, sw_type(&ps[0], ns)),
            _ => format!("{}.Result2<{}, {}>", ns, sw_type(&ps[0], ns), sw_type(&ps[1], ns)),
        },
    }
}

fn collect_types(t: &TypeRef, p: &Program, out: &mut BTreeSet<String>) {
    match t {
        TypeRef::Named(n, _) => {
            if out.contains(n) {
                return;
            }
            if let Some(s) = p.structs.iter().find(|s| &s.name == n) {
                out.insert(n.clone());
                for f in &s.fields {
                    collect_types(&f.ty, p, out);
                }
            } else if p.enums.iter().any(|e| &e.name == n) {
                out.insert(n.clone());
            }
        }
        TypeRef::List(x) | TypeRef::Map(x) | TypeRef::Opt(x) => collect_types(x, p, out),
        TypeRef::Fn(ps, r) => {
            for x in ps {
                collect_types(x, p, out);
            }
            if let Some(r) = r {
                collect_types(r, p, out);
            }
        }
    }
}

fn cap(s: &str) -> String {
    let mut c = s.chars();
    c.next().map(|f| f.to_uppercase().collect::<String>() + c.as_str()).unwrap_or_default()
}

pub fn swift(c: &Compilation, o: &Opts, is_module_file: impl Fn(u16) -> bool) -> Result<String, String> {
    let p = &c.program;
    let externs: Vec<_> = p.externs.iter().filter(|e| e.span.file != 0 && !is_module_file(e.span.file)).collect();
    let events: Vec<_> = p.events.iter().filter(|e| e.span.file != 0 && !is_module_file(e.span.file)).collect();
    if externs.is_empty() && events.is_empty() {
        return Err("no `extern fn` / `extern event` in this project (packages ship their own native code)".into());
    }
    let ns = format!("{}Vard", o.class);
    let mut types = BTreeSet::new();
    for e in &externs {
        for pa in &e.params {
            collect_types(&pa.ty, p, &mut types);
        }
        if let Some(r) = &e.ret {
            collect_types(r, p, &mut types);
        }
    }
    for e in &events {
        for pa in &e.params {
            collect_types(&pa.ty, p, &mut types);
        }
    }

    let mut s = String::new();
    s.push_str("// Generated by `vard bindings --swift` from the project's .vard files. Do not edit:\n");
    s.push_str("// regenerate after changing an `extern` declaration, then fix the Swift compile errors.\n");
    s.push_str("import Foundation\n\n");

    // ---- support namespace
    s.push_str(&format!(
        r#"/// Answers callbacks and receives events; the iOS host implements it over the C ABI
/// (`vard_callback(app, id, json, keep)` / `vard_emit(app, name, json)`).
public protocol {class}Host: AnyObject {{
    func callback(_ id: UInt64, _ json: String, keep: Bool)
    func emit(_ event: String, _ argsJSON: String)
}}

/// Glue between the Vard runtime's JSON bridge and `{class}`.
public enum {ns} {{
    public struct Signal {{
        let id: UInt64
        weak var host: {class}Host?
        public func fire() {{ host?.callback(id, "[]", keep: false) }}
        public func send() {{ host?.callback(id, "[]", keep: true) }}
    }}

    public struct Result<T: Encodable> {{
        let id: UInt64
        weak var host: {class}Host?
        public func resolve(_ value: T) {{ host?.callback(id, json(value), keep: false) }}
        /// a listener: deliver and stay subscribed
        public func send(_ value: T) {{ host?.callback(id, json(value), keep: true) }}
    }}

    public struct Result2<A: Encodable, B: Encodable> {{
        let id: UInt64
        weak var host: {class}Host?
        public func resolve(_ a: A, _ b: B) {{ host?.callback(id, "[\(json(a)),\(json(b))]", keep: false) }}
        public func send(_ a: A, _ b: B) {{ host?.callback(id, "[\(json(a)),\(json(b))]", keep: true) }}
    }}

    static func json<T: Encodable>(_ v: T) -> String {{
        guard let d = try? JSONEncoder().encode(v) else {{ return "null" }}
        return String(decoding: d, as: UTF8.self)
    }}

    static func value<T: Decodable>(_ args: [Any], _ i: Int, _ type: T.Type) -> T? {{
        let raw: Any = i < args.count ? args[i] : NSNull()
        guard let d = try? JSONSerialization.data(withJSONObject: [raw]) else {{ return nil }}
        return (try? JSONDecoder().decode([T].self, from: d))?.first
    }}

    static func callback(_ args: [Any], _ i: Int) -> UInt64 {{
        ((i < args.count ? args[i] : nil) as? [String: Any])?["$callback"].flatMap {{ ($0 as? NSNumber)?.uint64Value }} ?? 0
    }}
}}

"#,
        class = o.class,
        ns = ns
    ));

    // ---- data types
    for vname in &types {
        let name = sw_name(vname);
        if let Some(st) = p.structs.iter().find(|x| &x.name == vname) {
            s.push_str(&format!("public struct {}: Codable {{\n", name));
            for f in &st.fields {
                s.push_str(&format!("    public var {}: {}\n", ident(&f.name), sw_type(&f.ty, &ns)));
            }
            let params: Vec<String> = st.fields.iter().map(|f| format!("{}: {}", ident(&f.name), sw_type(&f.ty, &ns))).collect();
            s.push_str(&format!("\n    public init({}) {{\n", params.join(", ")));
            for f in &st.fields {
                s.push_str(&format!("        self.{} = {}\n", ident(&f.name), ident(&f.name)));
            }
            s.push_str("    }\n}\n\n");
        } else if let Some(en) = p.enums.iter().find(|x| &x.name == vname) {
            s.push_str(&format!("public enum {}: String, Codable, CaseIterable {{\n", name));
            for v in &en.variants {
                s.push_str(&format!("    case {}\n", ident(v)));
            }
            s.push_str("}\n\n");
        }
    }

    // ---- the module protocol and its dispatcher
    if !externs.is_empty() {
        s.push_str(&format!("/// Implement the app's native functions; the iOS host routes `extern fn` calls to `call`.\npublic protocol {}: AnyObject {{\n", o.class));
        for e in &externs {
            let params: Vec<String> = e.params.iter().map(|pa| format!("{}: {}", ident(&pa.name), sw_type(&pa.ty, &ns))).collect();
            let ret = e.ret.as_ref().map(|r| format!(" -> {}", sw_type(r, &ns))).unwrap_or_default();
            let src = c.sources.text(e.span).lines().next().unwrap_or("").trim().to_string();
            s.push_str(&format!("    /// `{}`\n    func {}({}){}\n", src, ident(&e.name), params.join(", "), ret));
        }
        s.push_str("}\n\n");
        s.push_str(&format!("public extension {} {{\n", o.class));
        s.push_str(&format!(
            "    /// `name` + JSON array of arguments → JSON result, or nil when `name` is not this module's.\n    func call(_ name: String, _ argsJSON: String, host: {}Host?) -> String? {{\n",
            o.class
        ));
        s.push_str("        let args = (try? JSONSerialization.jsonObject(with: Data(argsJSON.utf8))) as? [Any] ?? []\n");
        s.push_str("        switch name {\n");
        for e in &externs {
            s.push_str(&format!("        case \"{}\":\n", e.name));
            let mut call_args = Vec::new();
            for (i, pa) in e.params.iter().enumerate() {
                let arg = match &pa.ty {
                    TypeRef::Fn(ps, _) => {
                        let kind = match ps.len() {
                            0 => "Signal",
                            1 => "Result",
                            _ => "Result2",
                        };
                        format!("{}.{}(id: {}.callback(args, {}), host: host)", ns, kind, ns, i)
                    }
                    t => {
                        let ty = sw_type(t, &ns);
                        if matches!(t, TypeRef::Opt(_)) {
                            format!("{}.value(args, {}, {}.self) ?? nil", ns, i, ty)
                        } else {
                            s.push_str(&format!("            guard let a{} = {}.value(args, {}, {}.self) else {{ return \"null\" }}\n", i, ns, i, ty));
                            format!("a{}", i)
                        }
                    }
                };
                call_args.push(format!("{}: {}", ident(&pa.name), arg));
            }
            let invoke = format!("{}({})", ident(&e.name), call_args.join(", "));
            match &e.ret {
                Some(_) => s.push_str(&format!("            return {}.json({})\n", ns, invoke)),
                None => s.push_str(&format!("            {}\n            return \"null\"\n", invoke)),
            }
        }
        s.push_str("        default:\n            return nil\n        }\n    }\n}\n\n");
    }

    // ---- events
    if !events.is_empty() {
        s.push_str(&format!("public extension {}Host {{\n", o.class));
        for e in &events {
            let params: Vec<String> = e.params.iter().map(|pa| format!("{}: {}", ident(&pa.name), sw_type(&pa.ty, &ns))).collect();
            let parts: Vec<String> = e.params.iter().map(|pa| format!("{}.json({})", ns, ident(&pa.name))).collect();
            s.push_str(&format!(
                "    /// Deliver `extern event {}` to the app (any thread).\n    func emit{}({}) {{\n        emit(\"{}\", \"[\" + [{}].joined(separator: \",\") + \"]\")\n    }}\n",
                e.name,
                cap(&e.name),
                params.join(", "),
                e.name,
                parts.join(", ")
            ));
        }
        s.push_str("}\n");
    }
    Ok(s)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn swift_module_shape() {
        let src = r#"
struct Place { name: String, lat: Float, tags: [String] = [], note: String? = nil }
enum Mode { walk, drive }
extern fn searchPlaces(query: String, mode: Mode, done: fn([Place], String?))
extern fn distance(a: Place, b: Place) -> Float
extern event locationChanged(lat: Float, lng: Float)
view App { Text("x") }
"#;
        let c = vard_lang::compile(&[("app.vard".into(), src.into())]);
        assert!(!c.has_errors(), "{}", c.render_diags());
        let out = swift(&c, &Opts { package: "", class: "PlacesModule" }, |_| false).unwrap();
        for want in [
            "public struct Place: Codable {",
            "    public var lat: Double",
            "    public var tags: [String]",
            "    public var note: String?",
            "public enum Mode: String, Codable, CaseIterable {",
            "public protocol PlacesModule: AnyObject {",
            "    func searchPlaces(query: String, mode: Mode, done: PlacesModuleVard.Result2<[Place], String?>)",
            "    func distance(a: Place, b: Place) -> Double",
            "        case \"searchPlaces\":",
            "            guard let a1 = PlacesModuleVard.value(args, 1, Mode.self) else { return \"null\" }",
            "done: PlacesModuleVard.Result2(id: PlacesModuleVard.callback(args, 2), host: host)",
            "            return PlacesModuleVard.json(distance(a: a0, b: a1))",
            "    func emitLocationChanged(lat: Double, lng: Double) {",
        ] {
            assert!(out.contains(want), "missing `{}` in:\n{}", want, out);
        }
    }
}
